#!/usr/bin/env bash
# Rebuilds migrations/00001_baseline.sql from the Prisma migrations (ADR 0007).
# Until the cutover (B7) the baseline runs only in test databases, so it is
# rebuilt, not amended, when Prisma adds a migration. From B7 it is frozen.
#
#   scripts/make-baseline.sh postgresql://user@localhost:5432/postgres
#
# The URL names a PostgreSQL 16 where the user may create databases; a scratch
# database is created and dropped. Needs psql and pg_dump 16, and python3, on
# PATH (on Debian/Ubuntu: PATH=/usr/lib/postgresql/16/bin:$PATH).
set -euo pipefail
cd "$(dirname "$0")/.."

admin_url=${1:?usage: scripts/make-baseline.sh <admin database URL>}
out=migrations/00001_baseline.sql
scratch="lookly_baseline_$$"
migrations=(../web/prisma/migrations/*/)

if ! pg_dump --version | grep -qE ' 16\.'; then
  echo "pg_dump 16 is needed (found: $(pg_dump --version)); the baseline depends on its output" >&2
  exit 1
fi

# The temporary file sits next to the baseline (same filesystem: the final
# mv is atomic); its name does not end in .sql, so it is never embedded.
tmp=$(mktemp "$out.XXXXXX")
trap 'rm -f "$tmp"; psql "$admin_url" -q -c "DROP DATABASE IF EXISTS $scratch" >/dev/null' EXIT
psql "$admin_url" -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE $scratch"
scratch_url=$(python3 -I -c 'import sys, urllib.parse as u; p = u.urlsplit(sys.argv[1]); print(u.urlunsplit(p._replace(path="/" + sys.argv[2])))' "$admin_url" "$scratch")
sql() { psql "$scratch_url" -At -v ON_ERROR_STOP=1 -c "$1"; }

last=""
for dir in "${migrations[@]}"; do # the glob is sorted, as Prisma orders them
  # Prisma runs each migration.sql as one transaction.
  psql "$scratch_url" -v ON_ERROR_STOP=1 -q -1 -f "${dir}migration.sql" >/dev/null
  last=$(basename "$dir")
done

# The only data the Prisma migrations insert are the two SystemMarker rows
# appended below (their values are computed when the migration runs, so they
# cannot be dumped). Refuse if a migration starts inserting anything else.
rows=""
for table in $(sql "SELECT quote_ident(tablename) FROM pg_tables WHERE schemaname = 'public' AND tablename <> '_prisma_migrations' ORDER BY tablename"); do
  n=$(sql "SELECT count(*) FROM public.$table")
  if [[ $n != 0 ]]; then rows+="$table=$n "; fi
done
markers=$(sql 'SELECT string_agg("key", '"','"' ORDER BY "key") FROM "SystemMarker"')
if [[ "$rows" != '"SystemMarker"=2 ' || "$markers" != "legacyCutoverAt,migrationStartedAt" ]]; then
  echo "the Prisma migrations insert data this script does not reproduce: rows [$rows], markers [$markers]" >&2
  exit 1
fi

{
  echo "-- Baseline: the schema Prisma's migrations produce, up to and including"
  echo "-- $last (ADR 0007). Generated by scripts/make-baseline.sh;"
  echo "-- never edit by hand. No Down: the baseline is never rolled back."
  echo
  echo "-- +goose Up"
  echo "-- +goose StatementBegin"
  # Drop only pg_dump's own lines: its psql meta-commands, session settings,
  # section comments (and bare "--" lines, which are empty comments wherever
  # they stand) and the schema (which exists). Every other line is kept.
  pg_dump "$scratch_url" --schema-only --no-owner --no-privileges --no-comments -n public \
    | grep -vE '^(\\(un)?restrict [A-Za-z0-9]+$|SET (statement_timeout|lock_timeout|idle_in_transaction_session_timeout|transaction_timeout|client_encoding|standard_conforming_strings|check_function_bodies|xmloption|client_min_messages|row_security|default_tablespace|default_table_access_method) = .*;$|SELECT pg_catalog\.set_config\(.search_path., .., false\);$|--$|-- (Name: |Dumped (from|by) ).*$|-- PostgreSQL database dump( complete)?$|CREATE SCHEMA public;$)' \
    | cat -s
  # Data the Prisma migrations insert (20261006000300_session_families).
  echo "INSERT INTO public.\"SystemMarker\" (\"key\", \"value\") VALUES"
  echo "  ('migrationStartedAt', date_trunc('milliseconds', now() AT TIME ZONE 'UTC')),"
  echo "  ('legacyCutoverAt', date_trunc('milliseconds', clock_timestamp() AT TIME ZONE 'UTC') + interval '1 millisecond');"
  echo "-- +goose StatementEnd"
} > "$tmp"
# Only a complete baseline replaces the old one.
chmod 644 "$tmp"
mv "$tmp" "$out"
echo "wrote $out (Prisma up to $last)"
